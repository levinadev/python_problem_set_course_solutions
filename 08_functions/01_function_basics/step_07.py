"""
Урок 8.1 "Основы функций", шаг 7

Напишите функцию `rectangle(a, b)`, которая возвращает два значения: периметр и площадь
прямоугольника со сторонами `a` и `b`. Считайте два натуральных числа (каждое с новой строки) и
выведите периметр и площадь через пробел.
"""

def rectangle(a, b):
    return 2 * (a + b), a * b


perimeter, area = rectangle(int(input()), int(input()))
print(perimeter, area)
