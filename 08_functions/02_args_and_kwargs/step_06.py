"""
Урок 8.2 "Аргументы по умолчанию, *args, **kwargs", шаг 6

Напишите функцию `average(*args)`, которая возвращает среднее арифметическое переданных чисел,
округлённое функцией `round()` до двух знаков. Считайте строку с целыми числами через пробел,
передайте их в функцию и выведите результат.
"""

def average(*args):
    return round(sum(args) / len(args), 2)


numbers = [int(x) for x in input().split()]
print(average(*numbers))
