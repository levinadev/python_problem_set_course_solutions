"""
Урок 8.2 "Аргументы по умолчанию, *args, **kwargs", шаг 3

Напишите функцию `sum_nums(*args)`, которая возвращает сумму всех переданных чисел. Считайте строку
с целыми числами через пробел, вызовите функцию, передав ей все эти числа, и выведите результат.
"""

def sum_nums(*args):
    return sum(args)


numbers = [int(x) for x in input().split()]
print(sum_nums(*numbers))
