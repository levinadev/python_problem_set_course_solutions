"""
Урок 8.5 "Области видимости и замыкания", шаг 3

Напишите функцию `make_multiplier(k)`, которая возвращает новую функцию, умножающую свой аргумент на
`k` (замыкание). Считайте число `k` и строку с целыми числами через пробел. Создайте
функцию-множитель и выведите список результатов её применения к каждому числу.
"""

def make_multiplier(k):
    def multiply(x):
        return x * k
    return multiply


mul = make_multiplier(int(input()))
print([mul(int(x)) for x in input().split()])
