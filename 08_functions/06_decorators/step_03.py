"""
Урок 8.6 "Декораторы", шаг 3

Напишите декоратор `log`, который перед вызовом функции выводит `Вызов функции {имя функции}` (имя
хранится в атрибуте `__name__`). Украсьте им функцию `add(a, b)`, возвращающую сумму. Считайте два
целых числа (каждое с новой строки) и выведите результат `add`.
"""

def log(func):
    def wrapper(*args):
        print(f"Вызов функции {func.__name__}")
        return func(*args)
    return wrapper


@log
def add(a, b):
    return a + b


print(add(int(input()), int(input())))
