"""
Урок 8.3 "lambda, map, filter", шаг 7

На вход подаётся строка из слов через пробел. С помощью `sorted()` и `lambda` отсортируйте слова по
длине (слова одинаковой длины остаются в исходном порядке) и выведите их через пробел.
"""

words = input().split()
print(" ".join(sorted(words, key=lambda w: len(w))))
