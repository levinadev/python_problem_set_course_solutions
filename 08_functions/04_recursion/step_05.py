"""
Урок 8.4 "Рекурсия", шаг 5

Напишите рекурсивную функцию `power(a, n)`, которая возвращает `a` в степени `n` без оператора `**`
и функции `pow()`. Считайте целое `a` и неотрицательное целое `n` (каждое с новой строки) и выведите
результат.
"""

def power(a, n):
    if n == 0:
        return 1
    return a * power(a, n - 1)


a = int(input())
n = int(input())
print(power(a, n))
