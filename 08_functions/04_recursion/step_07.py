"""
Урок 8.4 "Рекурсия", шаг 7

Ханойская башня. На стержне 1 лежат `n` дисков (от 1 до 6). Нужно перенести их на стержень 3,
перекладывая по одному диску и никогда не кладя больший диск на меньший. Считайте `n` и выведите
оптимальную последовательность ходов, каждый ход на отдельной строке в формате `1 -> 3`.
"""

def hanoi(n, a, c, b):
    if n == 0:
        return
    hanoi(n - 1, a, b, c)
    print(f"{a} -> {c}")
    hanoi(n - 1, b, c, a)


hanoi(int(input()), 1, 3, 2)
