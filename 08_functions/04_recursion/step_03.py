"""
Урок 8.4 "Рекурсия", шаг 3

Последовательность Фибоначчи: `F(0) = 0`, `F(1) = 1`, `F(n) = F(n - 1) + F(n - 2)`. Напишите
рекурсивную функцию `fib(n)`. Считайте число `n` (от 0 до 20) и выведите `F(n)`.
"""

def fib(n):
    if n < 2:
        return n
    return fib(n - 1) + fib(n - 2)


print(fib(int(input())))
