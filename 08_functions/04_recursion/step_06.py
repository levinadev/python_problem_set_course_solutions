"""
Урок 8.4 "Рекурсия", шаг 6

Напишите рекурсивную функцию `reverse(s)`, которая возвращает строку в обратном порядке (без срезов
с шагом -1 и функции `reversed()`). Считайте строку и выведите результат.
"""

def reverse(s):
    if len(s) <= 1:
        return s
    return reverse(s[1:]) + s[0]


print(reverse(input()))
