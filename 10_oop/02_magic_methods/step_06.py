"""
Урок 10.2 "Магические методы (__init__, __str__)", шаг 6

Создайте класс `Temperature`, конструктор которого принимает температуру в градусах Цельсия.
Реализуйте `__str__()`, возвращающий строку `{c}°C = {f}°F`, где `f = c * 9 / 5 + 32` выведено с
одним знаком после точки. Считайте целое число и выведите объект.
"""

class Temperature:
    def __init__(self, c):
        self.c = c

    def __str__(self):
        return f"{self.c}°C = {self.c * 9 / 5 + 32:.1f}°F"


print(Temperature(int(input())))
