"""
Урок 10.6 "Методы класса и статические методы", шаг 2

Создайте класс `Converter` со статическим методом (`@staticmethod`) `c_to_f(c)`, который переводит
градусы Цельсия в Фаренгейты по формуле `c * 9 / 5 + 32`. Считайте целое число и выведите результат
`Converter.c_to_f()` с одним знаком после точки (объект класса создавать не нужно).
"""

class Converter:
    @staticmethod
    def c_to_f(c):
        return c * 9 / 5 + 32


print(f"{Converter.c_to_f(int(input())):.1f}")
