"""
Урок 3.3 "Вложенные условия", шаг 6

Считайте координаты точки `x` и `y` (каждое с новой строки, оба числа не равны нулю). Выведите номер
координатной четверти, в которой лежит точка: `1`, `2`, `3` или `4`.
"""

x = int(input())
y = int(input())
if x > 0:
    if y > 0:
        print(1)
    else:
        print(4)
else:
    if y > 0:
        print(2)
    else:
        print(3)
