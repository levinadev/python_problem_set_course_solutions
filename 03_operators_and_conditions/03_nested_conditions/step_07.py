"""
Урок 3.3 "Вложенные условия", шаг 7

Считайте температуру воды в градусах Цельсия (целое число). Выведите её состояние: `Лёд`, если
температура не выше 0; `Пар`, если не ниже 100; иначе `Вода`.
"""

t = int(input())
if t <= 0:
    print("Лёд")
elif t >= 100:
    print("Пар")
else:
    print("Вода")
