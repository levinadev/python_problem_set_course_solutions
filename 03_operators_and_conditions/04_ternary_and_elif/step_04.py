"""
Урок 3.4 "Тернарный оператор и цепочки условий", шаг 4

Считайте сумму покупки (целое число рублей). Скидка составляет 10% для сумм от 5000, 5% для сумм от
1000, для остальных скидки нет. Выведите сумму к оплате целым числом (дробная часть скидки
отбрасывается: скидка = сумма * процент // 100).
"""

s = int(input())
if s >= 5000:
    p = 10
elif s >= 1000:
    p = 5
else:
    p = 0
print(s - s * p // 100)
