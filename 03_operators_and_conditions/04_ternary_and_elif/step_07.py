"""
Урок 3.4 "Тернарный оператор и цепочки условий", шаг 7

Считайте длины трёх сторон треугольника (натуральные числа, каждое с новой строки; треугольник
гарантированно существует). Выведите его вид: `равносторонний`, `равнобедренный` или
`разносторонний`.
"""

a = int(input())
b = int(input())
c = int(input())
if a == b == c:
    print("равносторонний")
elif a == b or b == c or a == c:
    print("равнобедренный")
else:
    print("разносторонний")
