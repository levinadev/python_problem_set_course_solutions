"""
Урок 3.4 "Тернарный оператор и цепочки условий", шаг 6

Считайте время в формате `ЧЧ:ММ`. Выведите приветствие по часу: `Доброе утро` (с 5 до 11 часов
включительно), `Добрый день` (с 12 до 17), `Добрый вечер` (с 18 до 22), иначе `Доброй ночи`.
"""

h = int(input().split(":")[0])
if 5 <= h <= 11:
    print("Доброе утро")
elif 12 <= h <= 17:
    print("Добрый день")
elif 18 <= h <= 22:
    print("Добрый вечер")
else:
    print("Доброй ночи")
