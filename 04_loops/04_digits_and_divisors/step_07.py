"""
Урок 4.4 "Задачи на цифры и делители", шаг 7

Автобусный билет с шестизначным номером называется счастливым, если сумма первых трёх цифр равна
сумме последних трёх. Считайте номер билета (ровно 6 цифр, может начинаться с нуля) и выведите
`Счастливый` или `Обычный`.
"""

t = input()
left = sum(int(c) for c in t[:3])
right = sum(int(c) for c in t[3:])
print("Счастливый" if left == right else "Обычный")
