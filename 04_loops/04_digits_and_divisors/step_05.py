"""
Урок 4.4 "Задачи на цифры и делители", шаг 5

Число называется совершенным, если оно равно сумме всех своих делителей, кроме самого себя
(например, 6 = 1 + 2 + 3). Считайте натуральное число и выведите `True`, если оно совершенное, иначе
`False`.
"""

n = int(input())
print(n == sum(d for d in range(1, n) if n % d == 0))
