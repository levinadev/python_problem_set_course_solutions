"""
Урок 4.3 "break, continue и вложенные циклы", шаг 7

Считайте натуральное число `n` (не больше 9). Выведите числовой треугольник из `n` строк: в строке
номер `i` стоят числа от 1 до `i` через пробел.
"""

n = int(input())
for i in range(1, n + 1):
    for j in range(1, i + 1):
        print(j, end=" " if j < i else "\n")
