"""
Урок 4.3 "break, continue и вложенные циклы", шаг 4

Считайте натуральное число `n`. Выведите таблицу умножения для чисел от 1 до `n` в формате `a * b =
c`: сначала все строки для `a = 1` (`b` от 1 до `n`), затем для `a = 2` и так далее.
"""

n = int(input())
for a in range(1, n + 1):
    for b in range(1, n + 1):
        print(f"{a} * {b} = {a * b}")
