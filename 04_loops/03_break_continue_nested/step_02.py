"""
Урок 4.3 "break, continue и вложенные циклы", шаг 2

Считайте целое число `k` от 0 до 9. Выведите числа от 0 до 9 по порядку, но остановитесь (с помощью
`break`), когда дойдёте до числа `k`. Само число `k` выводить не нужно.
"""

k = int(input())
for i in range(10):
    if i == k:
        break
    print(i)
