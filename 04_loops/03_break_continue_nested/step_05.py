"""
Урок 4.3 "break, continue и вложенные циклы", шаг 5

Считывайте целые числа, пока не встретится 0. Каждое считанное число (кроме 0) выведите на отдельной
строке. Как только встретится 0, остановитесь с помощью `break`.
"""

while True:
    n = int(input())
    if n == 0:
        break
    print(n)
