"""
Урок 4.2 "Цикл while", шаг 4

Программа загадала число `7`. На вход программе подаются числа, попытки угадать загаданное число.
Считывайте числа до тех пор, пока не встретится `7`. После этого выведите `Угадал!`, а на следующей
строке число попыток, которое понадобилось (включая последнюю).
"""

attempts = 1
n = int(input())
while n != 7:
    n = int(input())
    attempts += 1
print("Угадал!")
print(attempts)
