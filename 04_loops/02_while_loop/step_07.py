"""
Урок 4.2 "Цикл while", шаг 7

Гипотеза Коллатца. Считайте натуральное число `n`. Пока `n` не равно 1, повторяйте: если `n` чётное,
разделите его на 2, иначе замените на `3 * n + 1`. Выведите, сколько шагов понадобилось, чтобы дойти
до 1.
"""

n = int(input())
steps = 0
while n != 1:
    if n % 2 == 0:
        n //= 2
    else:
        n = 3 * n + 1
    steps += 1
print(steps)
