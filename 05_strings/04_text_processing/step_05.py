"""
Урок 5.4 "Обработка текста: палиндромы, коды символов, шифры", шаг 5

Считайте строку и посчитайте в ней буквы, цифры и все остальные символы (включая пробелы). Выведите
результат в формате `Букв: 5, цифр: 2, других: 3`.
"""

s = input()
letters = sum(ch.isalpha() for ch in s)
digits = sum(ch.isdigit() for ch in s)
print(f"Букв: {letters}, цифр: {digits}, других: {len(s) - letters - digits}")
