"""
Урок 5.4 "Обработка текста: палиндромы, коды символов, шифры", шаг 3

Шифр Цезаря. Считайте строку из строчных латинских букв и пробелов и натуральное число `k` (каждое с
новой строки). Сдвиньте каждую букву на `k` позиций вперёд по алфавиту (после `z` идёт снова `a`),
пробелы оставьте без изменений. Выведите результат.
"""

text = input()
k = int(input())
result = ""
for ch in text:
    if ch == " ":
        result += ch
    else:
        result += chr((ord(ch) - ord("a") + k) % 26 + ord("a"))
print(result)
