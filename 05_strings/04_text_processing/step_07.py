"""
Урок 5.4 "Обработка текста: палиндромы, коды символов, шифры", шаг 7

Сжатие строки. Считайте непустую строку из латинских букв и замените каждую группу одинаковых подряд
идущих символов на символ и длину группы. Например, `aaabccdddd` превращается в `a3b1c2d4`.
"""

s = input()
result = ""
i = 0
while i < len(s):
    j = i
    while j < len(s) and s[j] == s[i]:
        j += 1
    result += s[i] + str(j - i)
    i = j
print(result)
