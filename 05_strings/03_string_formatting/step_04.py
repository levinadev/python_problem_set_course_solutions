"""
Урок 5.3 "Форматирование строк", шаг 4

Даны два вещественных числа, координаты точки.

Используя метод `format()`, выведите строку

    Точка: (5.20; -3.10)

Каждое число должно быть выведено с двумя знаками после запятой.
"""

x = float(input())
y = float(input())
print("Точка: ({:.2f}; {:.2f})".format(x, y))
