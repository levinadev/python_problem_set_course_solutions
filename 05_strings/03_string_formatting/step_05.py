"""
Урок 5.3 "Форматирование строк", шаг 5

Даны артикул товара и его вес.

Используя метод `format()`, выведите информацию в формате

    Артикул: A-105 | Вес: 1.250 кг

Вес необходимо вывести с тремя знаками после запятой.
"""

code = input()
weight = float(input())
print("Артикул: {} | Вес: {:.3f} кг".format(code, weight))
