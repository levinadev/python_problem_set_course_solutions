"""
Урок 5.3 "Форматирование строк", шаг 7

Даны название товара, цена (дробное число) и количество (целое число), каждое с новой строки.
Выведите строку чека в формате `Хлеб: 3 x 45.50 = 136.50`. Цену и итоговую сумму выведите с двумя
знаками после точки.
"""

name = input()
price = float(input())
qty = int(input())
print(f"{name}: {qty} x {price:.2f} = {price * qty:.2f}")
