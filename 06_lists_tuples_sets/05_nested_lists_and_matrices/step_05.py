"""
Урок 6.5 "Вложенные списки и матрицы", шаг 5

Дана квадратная матрица. Выведите сумму элементов её главной диагонали (от левого верхнего угла к
правому нижнему).

Формат ввода: в первой строке количество строк матрицы `n`, далее `n` строк с целыми числами через
пробел. Считать матрицу можно так: `matrix = [[int(x) for x in input().split()] for _ in
range(int(input()))]`
"""

matrix = [[int(x) for x in input().split()] for _ in range(int(input()))]
print(sum(matrix[i][i] for i in range(len(matrix))))
