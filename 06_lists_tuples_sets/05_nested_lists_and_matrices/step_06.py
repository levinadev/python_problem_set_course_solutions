"""
Урок 6.5 "Вложенные списки и матрицы", шаг 6

Дана матрица. Найдите её максимальный элемент и выведите через пробел его значение, номер строки и
номер столбца (нумерация с нуля). Если максимумов несколько, выведите тот, что встречается первым
при обходе строк сверху вниз и слева направо.

Формат ввода: в первой строке количество строк матрицы `n`, далее `n` строк с целыми числами через
пробел. Считать матрицу можно так: `matrix = [[int(x) for x in input().split()] for _ in
range(int(input()))]`
"""

matrix = [[int(x) for x in input().split()] for _ in range(int(input()))]
best = (matrix[0][0], 0, 0)
for i, row in enumerate(matrix):
    for j, x in enumerate(row):
        if x > best[0]:
            best = (x, i, j)
print(*best)
