"""
Урок 6.5 "Вложенные списки и матрицы", шаг 7

Считайте два натуральных числа `n` и `m` (каждое с новой строки). Заполните матрицу из `n` строк и
`m` столбцов числами от 1 до `n * m` "змейкой": чётные строки (нумерация с нуля) идут слева направо,
нечётные справа налево. Выведите матрицу, разделяя числа пробелом.
"""

n = int(input())
m = int(input())
for i in range(n):
    row = list(range(i * m + 1, i * m + m + 1))
    if i % 2 == 1:
        row.reverse()
    print(" ".join(map(str, row)))
