"""
Урок 6.3 "Кортежи", шаг 6

Даны имя и год рождения (каждое с новой строки). Упакуйте их в кортеж `person = (name, year)`, где
год записан целым числом. Затем распакуйте кортеж в две переменные и выведите строку `{имя} родился
в {год} году`.
"""

person = (input(), int(input()))
name, year = person
print(f"{name} родился в {year} году")
