"""
Урок 6.4 "Множества", шаг 3

Даны две строки, в каждой целые числа через пробел. Составьте из них множества `a` и `b` и выведите
в отсортированном виде элементы, которые есть в `a`, но нет в `b`.
"""

a = set(int(x) for x in input().split())
b = set(int(x) for x in input().split())
print(sorted(a - b))
