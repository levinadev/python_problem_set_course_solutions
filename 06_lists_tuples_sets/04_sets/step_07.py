"""
Урок 6.4 "Множества", шаг 7

Даны две строки, в каждой целые числа через пробел. Выведите в виде отсортированного списка числа,
которые встречаются ровно в одной из строк (симметрическая разность множеств).
"""

a = set(int(x) for x in input().split())
b = set(int(x) for x in input().split())
print(sorted(a ^ b))
