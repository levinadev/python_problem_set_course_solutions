"""
Урок 6.2 "Методы списков", шаг 5

Даны две строки, в каждой целые числа через пробел. Объедините числа из обеих строк в один список,
отсортируйте его по возрастанию и выведите.
"""

a = [int(x) for x in input().split()]
b = [int(x) for x in input().split()]
result = a + b
result.sort()
print(result)
