"""
Урок 6.2 "Методы списков", шаг 4

В первой строке различные целые числа через пробел, во второй одно из этих чисел `x`. Выведите
индекс числа `x` в списке, а затем список, отсортированный по убыванию.
"""

nums = [int(x) for x in input().split()]
x = int(input())
print(nums.index(x))
nums.sort(reverse=True)
print(nums)
