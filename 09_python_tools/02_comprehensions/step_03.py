"""
Урок 9.2 "Генераторы списков, словарей, множеств", шаг 3

Считайте два целых числа `a` и `b` (каждое с новой строки, `a <= b`). С помощью генератора словарей
создайте словарь, где ключами будут числа от `a` до `b` включительно, а значениями их квадраты, и
выведите его.
"""

a = int(input())
b = int(input())
print({x: x ** 2 for x in range(a, b + 1)})
