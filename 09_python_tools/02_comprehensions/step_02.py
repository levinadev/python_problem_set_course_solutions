"""
Урок 9.2 "Генераторы списков, словарей, множеств", шаг 2

Считайте два целых числа `a` и `b` (каждое с новой строки, `a <= b`). С помощью генератора списков
создайте список квадратов чисел от `a` до `b` включительно и выведите его.
"""

a = int(input())
b = int(input())
print([x ** 2 for x in range(a, b + 1)])
