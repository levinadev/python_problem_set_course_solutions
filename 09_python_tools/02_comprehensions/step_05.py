"""
Урок 9.2 "Генераторы списков, словарей, множеств", шаг 5

На вход подаётся строка из слов через пробел. С помощью генератора списков получите список слов
чётной длины, записанных в верхнем регистре, и выведите его.
"""

words = input().split()
print([w.upper() for w in words if len(w) % 2 == 0])
