"""
Урок 9.2 "Генераторы списков, словарей, множеств", шаг 6

На вход подаётся строка из различных слов через пробел. С помощью генератора словарей создайте
словарь, где ключом будет слово, а значением это же слово, записанное задом наперёд. Выведите
словарь.
"""

words = input().split()
print({w: w[::-1] for w in words})
