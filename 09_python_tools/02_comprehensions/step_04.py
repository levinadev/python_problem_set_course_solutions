"""
Урок 9.2 "Генераторы списков, словарей, множеств", шаг 4

На вход подаётся строка из целых чисел через пробел (могут повторяться и быть отрицательными). С
помощью генератора множеств создайте множество их квадратов. Отсортируйте его с помощью `sorted()` и
выведите получившийся список.
"""

numbers = [int(x) for x in input().split()]
squares = {x ** 2 for x in numbers}
print(sorted(squares))
