"""
Урок 9.4 "Обработка исключений", шаг 7

В первой строке целые числа через пробел, во второй индекс. Выведите элемент списка с этим индексом.
Если индекс выходит за границы списка, выведите `Нет такого индекса`, а если во второй строке не
число, выведите `Индекс должен быть числом`.
"""

numbers = input().split()
try:
    print(numbers[int(input())])
except IndexError:
    print("Нет такого индекса")
except ValueError:
    print("Индекс должен быть числом")
