"""
Урок 9.4 "Обработка исключений", шаг 6

Дано целое число.

Если число отрицательное, самостоятельно вызовите исключение:

    raise ValueError("Число должно быть положительным")

Обработайте это исключение и выведите сообщение:

    Число должно быть положительным

Если число неотрицательное, выведите его.
"""

n = int(input())
try:
    if n < 0:
        raise ValueError("Число должно быть положительным")
    print(n)
except ValueError as e:
    print(e)
