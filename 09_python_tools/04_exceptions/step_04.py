"""
Урок 9.4 "Обработка исключений", шаг 4

Дана строка.

Попробуйте преобразовать её в целое число.

Если преобразование прошло успешно, используя блок `else`, выведите квадрат числа.

Если возникла ошибка, выведите:

    Некорректный ввод
"""

s = input()
try:
    n = int(s)
except ValueError:
    print("Некорректный ввод")
else:
    print(n ** 2)
