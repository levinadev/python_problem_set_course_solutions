"""
Урок 9.4 "Обработка исключений", шаг 5

Даны два целых числа.

Попробуйте разделить первое число на второе.

После выполнения программы всегда выводите строку:

    Завершение программы

Используйте блок `finally`.

Если произошла ошибка деления на ноль, выведите:

    Деление на ноль невозможно!
"""

a = int(input())
b = int(input())
try:
    print(a / b)
except ZeroDivisionError:
    print("Деление на ноль невозможно!")
finally:
    print("Завершение программы")
