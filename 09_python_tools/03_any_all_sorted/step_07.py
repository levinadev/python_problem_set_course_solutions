"""
Урок 9.3 "Функции any(), all(), sorted()", шаг 7

На вход подаётся строка с результатами учеников в формате `имя:балл` через пробел. Отсортируйте
учеников по убыванию балла, а при равных баллах по имени в алфавитном порядке. Выведите имена через
пробел.
"""

people = [item.split(":") for item in input().split()]
people = sorted(people, key=lambda p: (-int(p[1]), p[0]))
print(" ".join(p[0] for p in people))
