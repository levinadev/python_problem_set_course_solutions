"""
Урок 9.1 "zip() и enumerate()", шаг 5

На вход подаётся строка с названиями цветов через пробел. Используя `enumerate`, выведите для
каждого цвета строку `Индекс: {i}, Цвет: {color}`.

Например, для входа `red green blue` программа должна вывести:

    Индекс: 0, Цвет: red
    Индекс: 1, Цвет: green
    Индекс: 2, Цвет: blue
"""

colors = input().split()
for i, color in enumerate(colors):
    print(f"Индекс: {i}, Цвет: {color}")
