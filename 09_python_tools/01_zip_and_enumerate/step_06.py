"""
Урок 9.1 "zip() и enumerate()", шаг 6

На вход подаётся строка из слов через пробел. С помощью `enumerate()` с параметром `start=1`
выведите нумерованный список: каждое слово на новой строке в формате `1. слово`.
"""

for i, word in enumerate(input().split(), start=1):
    print(f"{i}. {word}")
