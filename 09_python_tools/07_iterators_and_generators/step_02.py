"""
Урок 9.7 "Итераторы и генераторы (yield)", шаг 2

Напишите функцию-генератор `countdown(n)`, которая с помощью `yield` по очереди выдаёт числа от `n`
до 1. Считайте натуральное число и выведите все значения генератора через пробел.
"""

def countdown(n):
    while n > 0:
        yield n
        n -= 1


print(*countdown(int(input())))
