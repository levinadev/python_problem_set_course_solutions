"""
Урок 9.7 "Итераторы и генераторы (yield)", шаг 5

На вход подаётся строка из слов через пробел (не меньше трёх). Создайте из списка слов итератор
функцией `iter()`. Получите первые два слова с помощью `next()` и выведите их на отдельных строках,
а остальные слова выведите в третьей строке через пробел, пройдя по тому же итератору циклом `for`.
"""

it = iter(input().split())
print(next(it))
print(next(it))
print(" ".join(w for w in it))
