"""
Урок 9.7 "Итераторы и генераторы (yield)", шаг 4

Напишите бесконечный генератор `fibonacci()`, который выдаёт числа Фибоначчи 0, 1, 1, 2, 3, 5 и так
далее. Считайте натуральное число `n` и выведите через пробел первые `n` чисел, полученных из
генератора функцией `next()`.
"""

def fibonacci():
    a, b = 0, 1
    while True:
        yield a
        a, b = b, a + b


gen = fibonacci()
print(" ".join(str(next(gen)) for _ in range(int(input()))))
