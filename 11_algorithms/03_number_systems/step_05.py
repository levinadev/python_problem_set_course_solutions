"""
Урок 11.3 "Системы счисления", шаг 5

Считайте целое неотрицательное число `n` и основание `b` от 2 до 9 (каждое с новой строки). Выведите
запись числа `n` в системе счисления с основанием `b`.
"""

n = int(input())
b = int(input())
digits = ""
while n > 0:
    digits = str(n % b) + digits
    n //= b
print(digits or "0")
