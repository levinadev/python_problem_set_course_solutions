"""
Урок 11.3 "Системы счисления", шаг 2

Считайте целое неотрицательное число и выведите его двоичную запись, не используя функции `bin()` и
`format()`: делите число на 2 и собирайте остатки.
"""

n = int(input())
if n == 0:
    print(0)
else:
    digits = ""
    while n > 0:
        digits = str(n % 2) + digits
        n //= 2
    print(digits)
