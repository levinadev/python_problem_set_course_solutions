"""
Урок 11.5 "Итоговые задачи", шаг 9

Шахматный конь ходит буквой "Г": на две клетки по одной оси и на одну по другой. Считайте две клетки
доски в шахматной записи (например, `e2` и `f4`, каждую с новой строки) и выведите `True`, если конь
может попасть с первой клетки на вторую за один ход, иначе `False`.
"""

a = input()
b = input()
dx = abs(ord(a[0]) - ord(b[0]))
dy = abs(int(a[1]) - int(b[1]))
print({dx, dy} == {1, 2})
