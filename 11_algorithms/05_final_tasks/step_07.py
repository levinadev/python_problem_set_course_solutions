"""
Урок 11.5 "Итоговые задачи", шаг 7

Корзина покупок. В первой строке количество товаров `n`, далее `n` строк вида `название цена
количество` (цена и количество являются целыми числами). Выведите `Итого: {сумма}`, а во второй
строке `Самая дорогая позиция: {название}` (по стоимости цена × количество; при равенстве первая из
них).
"""

total = 0
best_name, best_cost = None, -1
for _ in range(int(input())):
    name, price, qty = input().split()
    cost = int(price) * int(qty)
    total += cost
    if cost > best_cost:
        best_name, best_cost = name, cost
print(f"Итого: {total}")
print(f"Самая дорогая позиция: {best_name}")
