"""
Урок 11.5 "Итоговые задачи", шаг 4

Проверка пароля. Считайте пароль и проверьте требования: длина не меньше 8 символов, есть хотя бы
одна цифра, есть заглавная латинская буква, есть строчная латинская буква. Для каждого
невыполненного требования выведите строку (в указанном порядке): `Слишком короткий`, `Нет цифры`,
`Нет заглавной буквы`, `Нет строчной буквы`. Если все требования выполнены, выведите `Надёжный
пароль`.
"""

p = input()
problems = []
if len(p) < 8:
    problems.append("Слишком короткий")
if not any(c.isdigit() for c in p):
    problems.append("Нет цифры")
if not any("A" <= c <= "Z" for c in p):
    problems.append("Нет заглавной буквы")
if not any("a" <= c <= "z" for c in p):
    problems.append("Нет строчной буквы")
print("\n".join(problems) if problems else "Надёжный пароль")
