"""
Урок 11.5 "Итоговые задачи", шаг 8

Банкомат выдаёт купюры номиналом 5000, 2000, 1000, 500 и 100 рублей. Считайте сумму (натуральное
число, кратное 100) и выдайте её минимальным количеством купюр. Для каждого использованного номинала
по убыванию выведите строку `номинал x количество`, например `5000 x 1`.
"""

amount = int(input())
for note in [5000, 2000, 1000, 500, 100]:
    if amount >= note:
        print(f"{note} x {amount // note}")
        amount %= note
