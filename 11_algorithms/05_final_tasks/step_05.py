"""
Урок 11.5 "Итоговые задачи", шаг 5

Считайте римское число (от 1 до 3999) и выведите его в десятичной записи. Римские цифры: I=1, V=5,
X=10, L=50, C=100, D=500, M=1000. Если цифра меньше следующей за ней, она вычитается (IV = 4, XC =
90).
"""

values = {"I": 1, "V": 5, "X": 10, "L": 50, "C": 100, "D": 500, "M": 1000}
s = input()
total = 0
for i in range(len(s)):
    v = values[s[i]]
    if i + 1 < len(s) and v < values[s[i + 1]]:
        total -= v
    else:
        total += v
print(total)
