"""
Урок 11.5 "Итоговые задачи", шаг 2

Анализ оценок. На вход подаётся строка с оценками от 1 до 5 через пробел. Выведите четыре строки:
`Средний балл: 4.25` (два знака после точки), `Лучшая оценка: 5`, `Худшая оценка: 3`, `Пятёрок: 2`.
"""

grades = [int(x) for x in input().split()]
print(f"Средний балл: {sum(grades) / len(grades):.2f}")
print(f"Лучшая оценка: {max(grades)}")
print(f"Худшая оценка: {min(grades)}")
print(f"Пятёрок: {grades.count(5)}")
