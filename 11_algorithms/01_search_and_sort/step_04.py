"""
Урок 11.1 "Поиск и сортировка", шаг 4

Сортировка пузырьком. На вход подаётся строка из целых чисел через пробел. Отсортируйте их по
возрастанию пузырьком: проходите по списку и меняйте местами соседние элементы, если левый больше
правого, пока список не станет упорядоченным. Выведите в первой строке отсортированный список, а во
второй сколько обменов было сделано.
"""

a = [int(x) for x in input().split()]
swaps = 0
for i in range(len(a)):
    for j in range(len(a) - 1 - i):
        if a[j] > a[j + 1]:
            a[j], a[j + 1] = a[j + 1], a[j]
            swaps += 1
print(a)
print(swaps)
