"""
Урок 11.1 "Поиск и сортировка", шаг 7

Сортировка подсчётом. На вход подаётся строка с оценками от 1 до 5 через пробел. Посчитайте, сколько
раз встречается каждая оценка, и выведите отсортированные по возрастанию оценки через пробел, не
используя `sort()` и `sorted()`: сначала все единицы, затем двойки и так далее.
"""

counts = [0] * 6
for x in input().split():
    counts[int(x)] += 1
result = []
for grade in range(1, 6):
    result += [str(grade)] * counts[grade]
print(" ".join(result))
