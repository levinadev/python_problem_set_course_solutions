"""
Урок 11.1 "Поиск и сортировка", шаг 3

Двоичный поиск. В первой строке различные целые числа через пробел в порядке возрастания, во второй
число `x`. Найдите индекс `x` двоичным поиском (на каждом шаге сравнивайте `x` с серединой отрезка и
отбрасывайте половину) и выведите его или `-1`, если числа нет.
"""

a = [int(x) for x in input().split()]
x = int(input())
lo, hi = 0, len(a) - 1
result = -1
while lo <= hi:
    mid = (lo + hi) // 2
    if a[mid] == x:
        result = mid
        break
    if a[mid] < x:
        lo = mid + 1
    else:
        hi = mid - 1
print(result)
