"""
Урок 11.4 "Стек и очередь", шаг 7

Считайте натуральное число `k` и строку с целыми числами через пробел (каждое с новой строки). С
помощью `deque(maxlen=k)` из модуля `collections` сохраните только последние `k` чисел и выведите их
через пробел. Если чисел меньше `k`, выведите все.
"""

from collections import deque

k = int(input())
last = deque(input().split(), maxlen=k)
print(" ".join(last))
