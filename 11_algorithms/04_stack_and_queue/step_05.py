"""
Урок 11.4 "Стек и очередь", шаг 5

Считалка. По кругу стоят `n` человек с номерами от 1 до `n`. Начиная с первого, считают до `k`;
`k`-й по счёту выбывает, и счёт продолжается со следующего. Считайте `n` и `k` (каждое с новой
строки) и выведите через пробел номера в порядке выбывания.
"""

from collections import deque

n = int(input())
k = int(input())
q = deque(range(1, n + 1))
out = []
while q:
    q.rotate(-(k - 1))
    out.append(q.popleft())
print(" ".join(map(str, out)))
