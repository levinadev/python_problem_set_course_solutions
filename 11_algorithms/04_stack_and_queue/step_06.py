"""
Урок 11.4 "Стек и очередь", шаг 6

Отмена действий. В первой строке количество команд `n`, далее `n` строк: `type слово` добавляет
слово в конец текста, `undo` отменяет последнее добавление (если отменять нечего, ничего не
происходит). Выведите итоговый текст, слова через пробел. Если текст пустой, выведите `(пусто)`.
"""

stack = []
for _ in range(int(input())):
    command = input().split()
    if command[0] == "type":
        stack.append(command[1])
    elif stack:
        stack.pop()
print(" ".join(stack) if stack else "(пусто)")
