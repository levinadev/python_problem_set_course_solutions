"""
Урок 11.2 "Простые числа, НОД и НОК", шаг 7

Считайте натуральное число `n` (до 1000) и выведите `n`-е по счёту простое число. Первое простое
число равно 2.
"""

n = int(input())
count = 0
x = 1
while count < n:
    x += 1
    if all(x % d for d in range(2, int(x ** 0.5) + 1)):
        count += 1
print(x)
