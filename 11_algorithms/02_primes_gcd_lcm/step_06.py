"""
Урок 11.2 "Простые числа, НОД и НОК", шаг 6

Считайте натуральное число больше 1 и выведите его разложение на простые множители в порядке
возрастания через пробел. Например, для 60 ответ `2 2 3 5`.
"""

n = int(input())
factors = []
d = 2
while d * d <= n:
    while n % d == 0:
        factors.append(d)
        n //= d
    d += 1
if n > 1:
    factors.append(n)
print(" ".join(map(str, factors)))
