"""
Урок 11.2 "Простые числа, НОД и НОК", шаг 2

Считайте натуральное число и выведите `True`, если оно простое, иначе `False`. Проверяйте делители
только до квадратного корня из числа.
"""

n = int(input())
is_prime = n > 1
d = 2
while d * d <= n:
    if n % d == 0:
        is_prime = False
        break
    d += 1
print(is_prime)
