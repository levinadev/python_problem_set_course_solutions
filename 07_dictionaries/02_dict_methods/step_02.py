"""
Урок 7.2 "Методы словарей", шаг 2

Дан словарь `config = {"theme": "dark", "font": "Arial"}`. Считайте ключ и с помощью метода `get()`
выведите его значение. Если такого ключа нет, выведите значение по умолчанию `"en"`.
"""

config = {"theme": "dark", "font": "Arial"}
key = input()
print(config.get(key, "en"))
