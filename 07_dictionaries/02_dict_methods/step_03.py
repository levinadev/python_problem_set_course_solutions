"""
Урок 7.2 "Методы словарей", шаг 3

Дан словарь `a = {"a": 1, "b": 2}`. Считайте два целых числа, значения для ключей `"b"` и `"c"`,
создайте из них словарь `b`, обновите словарь `a` с помощью `b` и выведите `a`.
"""

a = {"a": 1, "b": 2}
b = {"b": int(input()), "c": int(input())}
a.update(b)
print(a)
