"""
Урок 7.2 "Методы словарей", шаг 4

На вход подаётся строка из слов через пробел (без повторов). Создайте словарь, где ключами будут
слова, а значениями их длины. Выведите список всех ключей на одной строке и список всех значений на
другой.
"""

words = input().split()
data = {}
for w in words:
    data[w] = len(w)
print(list(data.keys()))
print(list(data.values()))
