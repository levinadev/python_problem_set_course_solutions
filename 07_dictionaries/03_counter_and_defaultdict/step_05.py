"""
Урок 7.3 "Подсчёт и группировка: Counter и defaultdict", шаг 5

Считайте строку и с помощью `Counter` из модуля `collections` найдите три самых частых символа
(пробелы не учитываются). Выведите каждый символ и количество через пробел на отдельной строке. При
равном количестве раньше идёт символ, который раньше встретился в строке. Гарантируется, что
различных символов (без пробелов) не меньше трёх.
"""

from collections import Counter

for ch, count in Counter(input().replace(" ", "")).most_common(3):
    print(ch, count)
