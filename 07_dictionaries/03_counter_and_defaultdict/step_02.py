"""
Урок 7.3 "Подсчёт и группировка: Counter и defaultdict", шаг 2

На вход подаётся строка из слов через пробел. Посчитайте, сколько раз встречается каждое слово, и
выведите результат в формате `слово: количество`, каждое слово на новой строке, в порядке первого
появления.
"""

counts = {}
for w in input().split():
    counts[w] = counts.get(w, 0) + 1
for w, c in counts.items():
    print(f"{w}: {c}")
