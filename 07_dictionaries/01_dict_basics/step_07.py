"""
Урок 7.1 "Создание и доступ к словарям", шаг 7

На вход подаётся строка с парами `ключ=значение` через пробел, например `a=1 b=2`. Значения являются
целыми числами, ключи не повторяются. Создайте из этих пар словарь и выведите его.
"""

d = {}
for pair in input().split():
    key, value = pair.split("=")
    d[key] = int(value)
print(d)
