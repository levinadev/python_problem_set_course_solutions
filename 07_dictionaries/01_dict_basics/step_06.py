"""
Урок 7.1 "Создание и доступ к словарям", шаг 6

На вход подаётся строка из слов через пробел (слова могут повторяться). Создайте словарь, где
ключами будут слова, а значениями их длины, и выведите количество ключей в словаре.
"""

words = input().split()
inventory = {}
for w in words:
    inventory[w] = len(w)
print(len(inventory))
